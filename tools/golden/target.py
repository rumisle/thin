"""Enumerate thin's target definitions and derived ISA tables.

The production tables are generated by tools.isagen from the pinned AMD XML.
No golden file is opened here. Form records come from the native target API.
"""

from __future__ import annotations

import json

from tools.golden import ROOT, encode
from tools.isagen import bundle, canonical
from tools.isagen.targets import TARGETS

BASE = "crates/thin-targets/tests/data/target/"
OUTPUTS = tuple(
    BASE + name
    for name in (
        "isa_tables.json.gz",
        "operand_table.json.gz",
        "forms.json.gz",
        "tables_manifest.json",
    )
)


def form_record(form):
    """Plain serialized form facts, evaluated through thin's Python target view."""
    from thin.target import PHYS, Flags

    flags = Flags.names(form.flags)
    return {
        "id": form.id,
        "name": form.name,
        "op": form.mnemonic,
        "base": form.base,
        "canon": form.canon,
        "kind": form.kind,
        "counter": form.counter,
        "unordered": form.unordered,
        "flags": [] if flags == "NONE" else flags.split("|"),
        "encoding": form.encoding,
        "arity": form.arity,
        "returning": form.returning,
        "slots": [
            {
                "kind": slot.kind,
                "dwords": slot.dwords,
                "role": slot.role,
                "type": slot.name,
                "sgpr_widths": sorted(slot.sgpr_widths),
                "modifiers": slot.modifiers,
                "literal": slot.literal,
                "widths": slot.widths,
            }
            for slot in form.slots
        ],
        "variadic": form.variadic,
        "fields": [
            {
                key: getattr(field, key)
                for key in ("name", "kind", "bits", "signed", "required", "choices")
            }
            for field in form.fields
        ],
        "implicit_defs": sorted(form.implicit_defs, key=list(PHYS).index),
        "implicit_uses": sorted(form.implicit_uses, key=list(PHYS).index),
        "mem_bytes": form.mem_bytes,
        "pseudo": form.pseudo or "None",
        "dpp": form.dpp,
        "dst_sel": form.dst_sel,
        "mem": form.mem,
        "wait_text": form.wait_text,
    }


def generate() -> dict[str, bytes]:
    """Evaluate complete form enumerations and production-table summaries."""
    from thin import _native
    from thin.target import Form

    name = _native.target_names()[0]
    source = ROOT / "crates" / "thin-targets" / "data" / name
    isa = json.loads((source / "isa_tables.json").read_text())
    operands = json.loads((source / "operand_table.json").read_text())
    forms = [form_record(Form(name, *raw)) for raw in _native.target_forms(name)]
    manifest = {
        "bundle": {
            "file": bundle.FILE,
            "url": bundle.URL,
            "sha256": bundle.SHA256,
            "member": TARGETS[name].member,
        },
        "isa_tables": {
            "encodings": len(isa["encodings"]),
            "ops": len(isa["ops"]),
            "sha256_canonical_json": canonical.sha256(isa),
        },
        "operand_table": {
            "forms": len(operands),
            "sha256_canonical_json": canonical.sha256(operands),
        },
    }
    return dict(
        zip(
            OUTPUTS,
            (
                encode(isa, compressed=True),
                encode(operands, compressed=True),
                encode(forms, compressed=True),
                encode(manifest),
            ),
            strict=True,
        )
    )
